/* Run against tests.screen_boards_preview and local Vite. All monitor data is synthetic. */
const {chromium}=require('playwright')
const assert=require('node:assert/strict')
const fs=require('node:fs/promises')
const path=require('node:path')

;(async()=>{
  const artifacts=process.env.SCREEN_ARTIFACTS||path.resolve('../../artifacts/screen-management-20261103')
  await fs.mkdir(artifacts,{recursive:true})
  const browser=await chromium.launch({headless:true,channel:'msedge'})
  const context=await browser.newContext({viewport:{width:1800,height:1100}})
  await context.addInitScript(()=>localStorage.setItem('ops-access-token','screen-preview-token'))
  const boardName=`浏览器验收大屏-${Date.now()}`
  const page=await context.newPage(),errors=[]
  page.on('pageerror',e=>errors.push(e.message))
  page.on('dialog',dialog=>dialog.accept())
  const api=async(method,url,data)=>{
    const response=await context.request.fetch('http://127.0.0.1:19091/api/v2/screen-boards'+url,{method,data,headers:{Authorization:'Bearer screen-preview-token'}})
    assert.ok(response.ok(),`${response.status()} ${await response.text()}`)
    return response.json()
  }
  try{
    await page.goto('http://127.0.0.1:15199/v3/#/screen/manage')
    await page.getByRole('button',{name:'＋ 新建大屏',exact:true}).click()
    await page.getByLabel('大屏名称',{exact:true}).fill(boardName)
    await page.locator('.property-panel label').filter({hasText:'大屏标题'}).locator('input').fill('自定义运维总览')
    await page.getByRole('button',{name:'深海蓝',exact:true}).click()
    await page.getByRole('button',{name:'＋ 文字说明',exact:true}).click()
    const textArea=page.locator('.property-panel textarea')
    await textArea.fill('浏览器验收使用模拟监控数据')
    await page.getByRole('button',{name:'保存草稿',exact:true}).click()
    await page.getByRole('status').filter({hasText:'草稿已保存'}).waitFor()
    let list=await api('GET',''),row=list.items.find(b=>b.name===boardName)
    assert.ok(row)
    assert.equal(row.config.widgets.length,6)
    assert.equal(row.config.theme.background,'#0b1526')
    // Remove/restore a component through the editor; no DOM ownership errors.
    await page.getByRole('button',{name:'复制组件',exact:true}).click()
    await page.getByRole('button',{name:'移除组件',exact:true}).click()
    await page.getByRole('button',{name:'保存草稿',exact:true}).click()
    await page.getByRole('status').filter({hasText:'草稿已保存'}).waitFor()
    // Drag the text widget into a free horizontal position, then resize it.
    const widget=page.locator('.grid-stack-item').last()
    await widget.scrollIntoViewIfNeeded()
    const handle=await widget.locator('.widget-handle').boundingBox()
    await page.mouse.move(handle.x+45,handle.y+15)
    await page.mouse.down();await page.mouse.move(handle.x+180,handle.y+15,{steps:15});await page.mouse.up()
    await page.waitForTimeout(400)
    const resize=widget.locator('.ui-resizable-se')
    const size=await resize.boundingBox()
    assert.ok(size,'resize handle exists')
    await page.mouse.move(size.x+size.width/2,size.y+size.height/2)
    await page.mouse.down();await page.mouse.move(size.x+size.width/2+95,size.y+size.height/2+60,{steps:15});await page.mouse.up()
    await page.getByRole('button',{name:'保存草稿',exact:true}).click()
    await page.getByRole('status').filter({hasText:'草稿已保存'}).waitFor()
    row=await api('GET',`/${row.id}`)
    const textWidget=row.config.widgets.find(w=>w.type==='text')
    assert.ok(textWidget.x>0,'drag persisted horizontal position')
    assert.ok(textWidget.w>6||textWidget.h>6,'resize persisted dimensions')
    await page.locator('.manager-head').scrollIntoViewIfNeeded()
    await page.screenshot({path:path.join(artifacts,'editor.png'),fullPage:true})
    await page.getByRole('button',{name:'预览草稿',exact:true}).click()
    await page.getByRole('dialog',{name:'大屏预览'}).getByRole('heading',{name:'自定义运维总览',exact:true}).waitFor()
    await page.getByRole('button',{name:'关闭预览',exact:true}).click()
    await page.getByRole('button',{name:'发布',exact:true}).click()
    await page.getByRole('status').filter({hasText:'已发布 v1'}).waitFor()
    await page.getByRole('button',{name:'← 返回列表',exact:true}).click()
    const card=page.locator('.board-card').filter({has:page.getByRole('heading',{name:boardName,exact:true})})
    await card.getByRole('button',{name:'设为默认',exact:true}).click()
    await page.getByRole('status').filter({hasText:'默认大屏已切换'}).waitFor()
    await page.getByRole('link',{name:'查看当前大屏 ↗'}).click()
    await page.getByRole('heading',{name:'自定义运维总览',exact:true}).waitFor()
    await page.reload()
    await page.getByRole('heading',{name:'自定义运维总览',exact:true}).waitFor()
    assert.equal(await page.locator('.grid-stack-item').count(),6)
    await page.screenshot({path:path.join(artifacts,'published.png'),fullPage:true})
    // A second browser context reads the same server-side published configuration.
    const second=await browser.newContext({viewport:{width:1440,height:900}})
    await second.addInitScript(()=>localStorage.setItem('ops-access-token','screen-preview-token'))
    const secondPage=await second.newPage()
    await secondPage.goto('http://127.0.0.1:15199/v3/#/screen-standalone')
    await secondPage.getByRole('heading',{name:'自定义运维总览',exact:true}).waitFor()
    await secondPage.setViewportSize({width:600,height:900})
    await secondPage.waitForTimeout(400)
    assert.equal(await secondPage.locator('.grid-stack-item').count(),6)
    await secondPage.screenshot({path:path.join(artifacts,'narrow.png'),fullPage:true})
    await second.close()
    // Draft updates do not leak into the default display; restore creates a new publication.
    row=await api('GET',`/${row.id}`)
    const oldTitle=row.config.title
    row.config.title='第二个发布版本'
    row=await api('PUT',`/${row.id}`,{name:row.name,config:row.config,is_template:true,revision:row.revision})
    assert.equal((await api('GET','/default')).config.title,oldTitle)
    row=await api('POST',`/${row.id}/publish`,{revision:row.revision})
    await page.goto('http://127.0.0.1:15199/v3/#/screen/manage')
    await page.reload()
    const currentCard=page.locator('.board-card').filter({has:page.getByRole('heading',{name:boardName,exact:true})})
    await currentCard.getByRole('button',{name:'版本',exact:true}).click()
    const v1=page.locator('.history-dialog article').filter({hasText:'v1 ·'})
    await v1.getByRole('button',{name:'恢复到草稿',exact:true}).click()
    await page.getByRole('status').filter({hasText:'已将 v1 恢复到草稿'}).waitFor()
    await page.getByRole('button',{name:'发布',exact:true}).click()
    await page.getByRole('status').filter({hasText:'已发布 v3'}).waitFor()
    assert.equal((await api('GET','/default')).config.title,oldTitle)
    assert.deepEqual(errors,[])
    await fs.writeFile(path.join(artifacts,'browser-result.json'),JSON.stringify({passed:true,source:'local isolated SQLite and synthetic monitoring fixtures',checks:['create','theme','text','component duplicate/remove','drag','resize','save','preview','publish','default','reload','second browser','narrow viewport','draft isolation','restore and republish'],errors},null,2))
    console.log('Browser acceptance passed; artifacts: '+artifacts)
  }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1})
